package com.example.myapplication;

public class Sampah {
    private String nama;
    private String harga;

    public Sampah(String nama, String harga) {
        this.nama = nama;
        this.harga = harga;
    }

    public String getNama() {
        return nama;
    }

    public String getHarga() {
        return harga;
    }
}
